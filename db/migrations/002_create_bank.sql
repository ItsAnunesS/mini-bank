CREATE TABLE BANK_USERS (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(120) NOT NULL,
    EMAIL VARCHAR(254) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(256) NOT NULL,
    ROLE VARCHAR(10) NOT NULL CHECK (ROLE IN ('ADMIN', 'CUSTOMER')),
    FAILED_LOGINS INTEGER NOT NULL DEFAULT 0,
    LOCKED_UNTIL TIMESTAMP,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
);
CREATE TABLE BANK_SESSIONS (
    TOKEN_HASH CHAR(64) NOT NULL PRIMARY KEY,
    USER_ID BIGINT NOT NULL REFERENCES BANK_USERS(ID),
    EXPIRES_AT TIMESTAMP NOT NULL
);
CREATE TABLE BANK_ACCOUNTS (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_ID BIGINT NOT NULL REFERENCES BANK_USERS(ID),
    STATUS VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (STATUS IN ('ACTIVE', 'BLOCKED')),
    BALANCE DECIMAL(15,2) NOT NULL DEFAULT 0 CHECK (BALANCE >= 0),
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
);
CREATE TABLE BANK_TRANSACTIONS (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ACTOR_ID BIGINT NOT NULL REFERENCES BANK_USERS(ID),
    REQUEST_KEY CHAR(36) NOT NULL,
    KIND VARCHAR(10) NOT NULL CHECK (KIND IN ('DEPOSIT', 'TRANSFER')),
    SOURCE_ID BIGINT REFERENCES BANK_ACCOUNTS(ID),
    TARGET_ID BIGINT NOT NULL REFERENCES BANK_ACCOUNTS(ID),
    AMOUNT DECIMAL(9,2) NOT NULL CHECK (AMOUNT > 0),
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    UNIQUE (ACTOR_ID, REQUEST_KEY)
);
CREATE TABLE BANK_ENTRIES (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TRANSACTION_ID BIGINT NOT NULL REFERENCES BANK_TRANSACTIONS(ID),
    ACCOUNT_ID BIGINT NOT NULL REFERENCES BANK_ACCOUNTS(ID),
    DIRECTION CHAR(1) NOT NULL CHECK (DIRECTION IN ('+', '-')),
    AMOUNT DECIMAL(9,2) NOT NULL CHECK (AMOUNT > 0),
    BALANCE_AFTER DECIMAL(15,2) NOT NULL CHECK (BALANCE_AFTER >= 0),
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    UNIQUE (TRANSACTION_ID, ACCOUNT_ID)
);
CREATE TABLE BANK_AUDIT (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ACTOR_ID BIGINT NOT NULL REFERENCES BANK_USERS(ID),
    ACTION VARCHAR(30) NOT NULL,
    SUBJECT_ID BIGINT NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
);
CREATE INDEX BANK_ACCOUNTS_OWNER ON BANK_ACCOUNTS(USER_ID, ID);
CREATE INDEX BANK_ENTRIES_ACCOUNT ON BANK_ENTRIES(ACCOUNT_ID, ID);
CREATE INDEX BANK_SESSIONS_EXPIRY ON BANK_SESSIONS(EXPIRES_AT)
