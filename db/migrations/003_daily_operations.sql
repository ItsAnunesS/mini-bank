ALTER TABLE BANK_TRANSACTIONS ADD CONSTRAINT BANK_TRANSACTION_KIND CHECK (KIND IN ('DEPOSIT', 'TRANSFER', 'INTEREST', 'REVERSAL'));
CREATE TABLE BANK_SAVINGS (
    ACCOUNT_ID BIGINT NOT NULL PRIMARY KEY REFERENCES BANK_ACCOUNTS(ID),
    ANNUAL_RATE DECIMAL(5,2) NOT NULL DEFAULT 3.65 CHECK (ANNUAL_RATE = 3.65)
);
CREATE TABLE BANK_REVERSALS (
    ORIGINAL_ID BIGINT NOT NULL PRIMARY KEY REFERENCES BANK_TRANSACTIONS(ID),
    TRANSACTION_ID BIGINT NOT NULL UNIQUE REFERENCES BANK_TRANSACTIONS(ID),
    REASON VARCHAR(240) NOT NULL
);
CREATE TABLE BANK_REPORTS (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ACTOR_ID BIGINT NOT NULL REFERENCES BANK_USERS(ID),
    MODE VARCHAR(10) NOT NULL CHECK (MODE IN ('CLOSE', 'RECONCILE')),
    REPORT_DATE DATE NOT NULL,
    STATUS VARCHAR(10) NOT NULL CHECK (STATUS IN ('OK', 'MISMATCH')),
    ACCOUNT_COUNT INTEGER NOT NULL DEFAULT 0,
    MISMATCH_COUNT INTEGER NOT NULL DEFAULT 0,
    TOTAL_INTEREST DECIMAL(19,2) NOT NULL DEFAULT 0,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
);
CREATE TABLE BANK_REPORT_ACCOUNTS (
    REPORT_ID BIGINT NOT NULL REFERENCES BANK_REPORTS(ID),
    ACCOUNT_ID BIGINT NOT NULL REFERENCES BANK_ACCOUNTS(ID),
    ACCOUNT_TYPE VARCHAR(10) NOT NULL,
    ACCOUNT_STATUS VARCHAR(10) NOT NULL,
    BALANCE_BEFORE DECIMAL(15,2) NOT NULL,
    LEDGER_BALANCE DECIMAL(19,2) NOT NULL,
    LAST_BALANCE DECIMAL(15,2) NOT NULL,
    DIFFERENCE DECIMAL(19,2) NOT NULL,
    ISSUE VARCHAR(30) NOT NULL,
    INTEREST_AMOUNT DECIMAL(15,2) NOT NULL DEFAULT 0,
    BALANCE_AFTER DECIMAL(15,2) NOT NULL,
    PRIMARY KEY (REPORT_ID, ACCOUNT_ID)
);
CREATE TABLE BANK_DAILY_CLOSES (
    CLOSE_DATE DATE NOT NULL PRIMARY KEY,
    REPORT_ID BIGINT NOT NULL UNIQUE REFERENCES BANK_REPORTS(ID)
);
CREATE INDEX BANK_REPORTS_DATE ON BANK_REPORTS(REPORT_DATE, ID);
