ALTER TABLE BANK_ACCOUNTS ADD CONSTRAINT BANK_ACCOUNT_STATUS CHECK (STATUS IN ('ACTIVE', 'BLOCKED', 'PENDING'));
CREATE TABLE BANK_ACCOUNT_APPROVALS (
    ACCOUNT_ID BIGINT NOT NULL PRIMARY KEY REFERENCES BANK_ACCOUNTS(ID),
    REQUESTED_BY BIGINT NOT NULL REFERENCES BANK_USERS(ID),
    REQUEST_KEY CHAR(36) NOT NULL,
    APPROVED_BY BIGINT REFERENCES BANK_USERS(ID),
    REQUESTED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    APPROVED_AT TIMESTAMP,
    UNIQUE (REQUESTED_BY, REQUEST_KEY),
    CHECK ((APPROVED_BY IS NULL AND APPROVED_AT IS NULL) OR (APPROVED_BY IS NOT NULL AND APPROVED_AT IS NOT NULL))
);
