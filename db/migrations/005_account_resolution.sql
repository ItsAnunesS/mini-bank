ALTER TABLE BANK_ACCOUNTS DROP CONSTRAINT BANK_ACCOUNT_STATUS;
ALTER TABLE BANK_ACCOUNTS ADD CONSTRAINT BANK_ACCOUNT_STATUS CHECK (STATUS IN ('ACTIVE', 'BLOCKED', 'PENDING', 'REJECTED', 'CANCELLED'));
CREATE TABLE BANK_ACCOUNT_RESOLUTIONS (
    ACCOUNT_ID BIGINT NOT NULL PRIMARY KEY REFERENCES BANK_ACCOUNTS(ID),
    STATUS VARCHAR(10) NOT NULL CHECK (STATUS IN ('REJECTED', 'CANCELLED')),
    REASON VARCHAR(240),
    RESOLVED_BY BIGINT NOT NULL REFERENCES BANK_USERS(ID),
    RESOLVED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CHECK ((STATUS = 'REJECTED' AND REASON IS NOT NULL AND LENGTH(TRIM(REASON)) >= 5) OR (STATUS = 'CANCELLED' AND REASON IS NULL))
);
