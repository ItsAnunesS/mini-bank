CREATE TABLE BANK_NOTIFICATIONS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_ID BIGINT NOT NULL REFERENCES BANK_USERS(ID),
    ACCOUNT_ID BIGINT NOT NULL REFERENCES BANK_ACCOUNTS(ID),
    KIND VARCHAR(20) NOT NULL CHECK (KIND IN ('ACCOUNT_APPROVED', 'ACCOUNT_REJECTED')),
    REASON VARCHAR(240),
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    READ_AT TIMESTAMP,
    UNIQUE (ACCOUNT_ID, KIND),
    CHECK ((KIND = 'ACCOUNT_REJECTED' AND REASON IS NOT NULL) OR (KIND = 'ACCOUNT_APPROVED' AND REASON IS NULL))
);
CREATE INDEX BANK_NOTIFICATION_OWNER ON BANK_NOTIFICATIONS (USER_ID, ID DESC);
