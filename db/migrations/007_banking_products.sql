CREATE TABLE BANK_FEES (
 ACCOUNT_ID BIGINT NOT NULL REFERENCES BANK_ACCOUNTS(ID),
 FEE_MONTH DATE NOT NULL,
 TRANSACTION_ID BIGINT NOT NULL UNIQUE REFERENCES BANK_TRANSACTIONS(ID),
 PRIMARY KEY (ACCOUNT_ID, FEE_MONTH)
);
CREATE TABLE BANK_LOANS (
 ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 ACCOUNT_ID BIGINT NOT NULL REFERENCES BANK_ACCOUNTS(ID),
 USER_ID BIGINT NOT NULL REFERENCES BANK_USERS(ID),
 REQUEST_KEY CHAR(36) NOT NULL,
 PRINCIPAL DECIMAL(9,2) NOT NULL CHECK (PRINCIPAL BETWEEN 100 AND 100000),
 MONTHS INTEGER NOT NULL CHECK (MONTHS BETWEEN 3 AND 60),
 ANNUAL_RATE DECIMAL(5,2) NOT NULL DEFAULT 6 CHECK (ANNUAL_RATE = 6),
 STATUS VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (STATUS IN ('PENDING','ACTIVE','REJECTED','PAID')),
 REASON VARCHAR(240),
 DECIDED_BY BIGINT REFERENCES BANK_USERS(ID),
 DISBURSEMENT_ID BIGINT REFERENCES BANK_TRANSACTIONS(ID),
 CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
 APPROVED_AT TIMESTAMP,
 UNIQUE (USER_ID, REQUEST_KEY)
);
CREATE TABLE BANK_INSTALLMENTS (
 LOAN_ID BIGINT NOT NULL REFERENCES BANK_LOANS(ID),
 NUMBER INTEGER NOT NULL,
 DUE_DATE DATE NOT NULL,
 CAPITAL DECIMAL(9,2) NOT NULL CHECK (CAPITAL > 0),
 INTEREST DECIMAL(9,2) NOT NULL CHECK (INTEREST >= 0),
 AMOUNT DECIMAL(9,2) NOT NULL,
 REMAINING DECIMAL(9,2) NOT NULL CHECK (REMAINING >= 0),
 TRANSACTION_ID BIGINT REFERENCES BANK_TRANSACTIONS(ID),
 PAID_AT TIMESTAMP,
 PRIMARY KEY (LOAN_ID, NUMBER),
 CHECK (AMOUNT = CAPITAL + INTEREST)
);
CREATE INDEX BANK_LOANS_ACCOUNT ON BANK_LOANS(ACCOUNT_ID, STATUS);
CREATE INDEX BANK_LOANS_OWNER ON BANK_LOANS(USER_ID, ID);
CREATE INDEX BANK_TRANSACTIONS_DAILY ON BANK_TRANSACTIONS(SOURCE_ID, CREATED_AT);
CREATE INDEX BANK_ENTRIES_MONTH ON BANK_ENTRIES(ACCOUNT_ID, CREATED_AT, ID);
CREATE UNIQUE INDEX BANK_LOAN_DISBURSEMENT ON BANK_LOANS(DISBURSEMENT_ID) EXCLUDE NULL KEYS;
CREATE UNIQUE INDEX BANK_INSTALLMENT_PAYMENT ON BANK_INSTALLMENTS(TRANSACTION_ID) EXCLUDE NULL KEYS;
